  organization: {
    id: string;
    name: string;
    currency: string;
    locale: string;
    timeZone: string;
    today: string;
  };
  branches: { id: string; name: string }[];
  branchId: string;
  q: string;
  page: number;
  total: number;
  rows: Employee[];
  selected: Employee | null;
  charges: PayrollCharge[];
  chargeTotal: number;
  chargePage: number;
  selectedCharge: PayrollCharge | null;
  payments: PayrollPayment[];
  paymentTotal: number;
  paymentPage: number;
  summary: {
    currency: string;
    chargedMinor: string;
    paidMinor: string;
    balanceMinor: string;
  }[];
  trainerOptions: { id: string; name: string; branchIds: string[] }[];
  canManageEmployees: boolean;
  canManageSettings: boolean;
  canManageMembers: boolean;
  canReadPlans: boolean;
  canReadBilling: boolean;
