export type Employee = {
  id: string;
  branchId: string;
  branchName: string;
  trainerId: string | null;
  name: string;
  title: string;
  phone: string;
  email: string;
  startOn: string;
  active: boolean;
  salaryMinor: string | null;
  currency: string;
  payDay: number;
  version: number;
};
export type PayrollCharge = {
  id: string;
  employeeId: string;
  branchId: string;
  employeeName: string;
  employeeTitle: string;
  period: string;
  dueOn: string;
  amountMinor: string;
  currency: string;
  paidMinor: string;
  balanceMinor: string;
  voided: boolean;
  voidReason: string;
};
export type PayrollPayment = {
  id: string;
  expenseId: string;
  number: string;
  amountMinor: string;
  currency: string;
  paidOn: string;
  method: string;
  reference: string;
  reversed: boolean;
  reversalReason: string | null;
};
