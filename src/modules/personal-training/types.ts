import type { z } from "zod";
import type { agendaQuery } from "./schemas";
export type Assignment = {
  id: string;
  memberId: string;
  memberName: string;
  memberCode: string;
  trainerId: string;
  trainerName: string;
  branchId: string;
  branchName: string;
  startOn: string;
  endOn: string | null;
  active: boolean;
  version: number;
  archived: boolean;
};
export type PersonalSession = {
  id: string;
  assignmentId: string;
  memberId: string;
  memberName: string;
  memberCode: string;
  trainerId: string;
  trainerName: string;
  branchId: string;
  branchName: string;
  roomId: string | null;
  roomName: string | null;
  title: string;
  startsAt: string;
  endsAt: string;
  localDate: string;
  cancelled: boolean;
  cancellationReason: string;
  upcoming: boolean;
  version: number;
};
export type Agenda = {
  organization: {
    id: string;
    name: string;
    locale: string;
    timeZone: string;
    today: string;
  };
  branches: { id: string; name: string }[];
  trainers: {
    id: string;
    name: string;
    active: boolean;
    branchIds: string[];
  }[];
  trainerId: string | null;
  rooms: { id: string; name: string; branchId: string }[];
  assignments: Assignment[];
  sessionAssignments: Assignment[];
  assignmentTotal: number;
  assignmentPage: number;
  sessions: PersonalSession[];
  total: number;
  page: number;
  from: string;
  to: string;
  query: z.infer<typeof agendaQuery>;
  own: boolean;
  canManage: boolean;
  canBook: boolean;
  canManageSettings: boolean;
  canManageMembers: boolean;
  canReadPlans: boolean;
  canReadBilling: boolean;
  requestId: string;
};
